def _runs(rows):
    """그림 → [(줄, 시작 칸, 끝 칸)] 같은 줄에서 이어진 '#' 칸을 하나로."""
    out = []
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            if row[c] != "#":
                c += 1
                continue
            c1 = c
            while c1 + 1 < len(row) and row[c1 + 1] == "#":
                c1 += 1
            out.append((r, c, c1))
            c = c1 + 1
    return out


ROT_FRONT = (0.0, 0.0, math.pi / 2)         # 정면(-y쪽)을 보는 도트 판의 상자 회전 (두께가 y 방향)


def wcells(G, rows, center, right, up, cell, col, thick=0.02, rot=ROT_FRONT, k=1.0):
    """발광 상자 인스턴스로 도트 그림: rows의 '#'를 칸으로. center = 그림 가운데, right·up = 그림이 놓인 면의 방향(단위벡터), rot = 상자 회전. k = 크기 배율."""
    h, w = len(rows), len(rows[0])
    c0 = np.asarray(center, float)
    r_, u_ = np.asarray(right, float), np.asarray(up, float)
    for r, c, c1 in _runs(rows):
        x = ((c + c1 + 1) / 2.0 - w / 2.0) * cell
        z = (h / 2.0 - r - 0.5) * cell
        G.c(c0 + (r_ * x + u_ * z) * k, (thick * k, ((c1 - c + 1) * cell - 0.05 * cell) * k, cell * 0.95 * k), col, rot)


def vcells(v, rows, x, y, z, cell, col, face="y", glow=False, depth=0.03):
    """세트(Vox)에 도트 그림을 상자로 박음. face='y'면 -y쪽을 봄(가로 = +x), 'x'면 +x쪽을 봄(가로 = +y). (x, y, z) = 왼쪽 위 칸 가운데."""
    for r, c, c1 in _runs(rows):
        z1, z0 = z - r * cell + cell / 2, z - r * cell - cell / 2
        if face == "y":
            v.box(x + (c - 0.5) * cell, x + (c1 + 0.5) * cell, y - depth, y, z0, z1, col, jit=0, glow=glow)
        else:
            v.box(x - depth, x, y + (c - 0.5) * cell, y + (c1 + 0.5) * cell, z0, z1, col, jit=0, glow=glow)


def vtext(v, txt, c, ztop, wall, cell, col, glow=True, depth=0.03, face="y"):
    """세트 벽에 한글 도트 글씨 간판: 벽을 따라 가운데 c, 위 끝 ztop. face='y'면 -y쪽을 보고 뒷면이 wall(y 좌표), face='x'면 +x쪽을 보고 앞면이 wall(x 좌표)."""
