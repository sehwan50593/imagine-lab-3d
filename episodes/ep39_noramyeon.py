def _shelf_items():
    """뒷벽 진열대 상품 목록 [dict(kind, x, z0, tier, col, vis, tv0, tv2, take)] — 퐁 하는 때를 훅(tv0)·2번 줄(tv2)마다 정함."""
    rs = np.random.default_rng(39)
    items = []
    for kind, n, x0, x1 in (("cup", CUP_N, SHELF_X0 + 0.05, SHELF_XM - 0.05), ("bag", BAG_N, SHELF_XM + 0.05, SHELF_X1 - 0.05)):
        pitch = (x1 - x0) / n
        cols = BAGC if kind == "bag" else CUPC
        for tier in range(4):
            for k in range(n):
                x = x0 + pitch * (k + 0.5)
                items.append(dict(kind=kind, x=x, z0=TIERS[tier], tier=tier, col=cols[int(rs.integers(len(cols)))],
                                  vis=HOOK_VIS[0] <= x <= HOOK_VIS[1], take=None))
    vis = [it for it in items if it["vis"]]
    key = [it["x"] + 0.45 * it["tier"] + 0.35 * rs.uniform(-1, 1) for it in vis]       # 왼쪽 아래에서 오른쪽 위로 쓸어 가며 퐁퐁
    for rank, j in enumerate(np.argsort(key)):
        r = rank / max(len(vis) - 1, 1)
        vis[j]["tv0"] = 0.03 + 0.77 * r
        vis[j]["tv2"] = 1.25 + 0.70 * (1.0 - r)                                        # 2번 줄은 "한 봉지도 없어요"에 맞춰, 반대로 오른쪽에서 왼쪽으로
    for it in items:
        if not it["vis"]:
            it["tv0"], it["tv2"] = 0.2 + 0.7 * rs.random(), 1.3 + 0.65 * rs.random()
    bags = sorted((it for it in items if it["kind"] == "bag" and it["tier"] in (1, 2) and abs(it["x"] - 0.45) < 1.4),
                  key=lambda it: abs(it["x"] - 0.45))
    for n, it in enumerate(bags[:6]):                                                   # 1번 줄에 카트로 날아가는 봉지
        it["take"] = (0.25 + 0.38 * n, n)
    return items


