def _mix(a, b, k):
    return tuple(tuple(lerp(x, y, k) for x, y in zip(p, q)) if isinstance(p, tuple) else lerp(p, q, k) for p, q in zip(a, b))


def day_k(u):
    """천 년 뒤 줄: 밤 → 낮 → 밤 → 낮 (두 번 돌아감)."""
    return 0.5 - 0.5 * math.cos(2 * math.pi * 2.0 * u)


