def _crack_pts():
    """달 위 번개 모양 금: (가로, 세로) 달 지름 단위, 0.03 간격 점."""
    main = [(-0.5, 0.12), (-0.32, 0.02), (-0.2, 0.14), (-0.05, 0.0), (0.1, -0.1), (0.25, 0.02), (0.38, -0.12), (0.5, -0.04)]
    branch = [(-0.05, 0.0), (-0.1, -0.2), (0.0, -0.35), (-0.06, -0.5)]
    out = []
    for path in (main, branch):
        for (x0, y0), (x1, y1) in zip(path[:-1], path[1:]):
            n = max(1, int(math.hypot(x1 - x0, y1 - y0) / 0.03))
            out += [(lerp(x0, x1, q / n), lerp(y0, y1, q / n)) for q in range(n)]
    return out


