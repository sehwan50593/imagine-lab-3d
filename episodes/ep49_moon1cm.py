def moon_sky(cam, G, OR, nx, ny, dfrac, crack=0.0, ring=0.0, tone=1.0):
    """하늘의 달: 카메라 앞 300m 발광 구 + 분화구. dfrac = 화면 높이에 대한 지름 비율. crack 0~1 금, ring 0~1 번쩍 고리."""
    D = 300.0
    d = dfrac * D * 24.0 / cam["lens"]
    R = d / 2
    C = cam["loc"] + screen_dir(cam, nx, ny) * D
    OR.orbw(C, d, tuple(c * tone for c in MOON_C))
    for a, b, rel in CRATERS:
        n = a * cam["right"] + b * cam["up"] - math.sqrt(max(0.0, 1 - a * a - b * b)) * cam["fwd"]
        n = n / np.linalg.norm(n)
        OR.orbw(C + n * (R - 0.3 * rel * R), rel * d, tuple(c * tone for c in CR_C))
    df = max(D - R - 1.0, 5.0)
    s = 0.028 * dfrac
    if crack > 0.01:
        for px, py in CRACK[:int(len(CRACK) * crack)]:
            sprite(G, cam, nx + px * dfrac / 0.28125, ny + py * dfrac / 0.5, s, s, CRACK_C, df, 0.4)
    if 0.0 < ring < 1.0:
        r = dfrac * (0.5 + 0.9 * ring)
        sz = 0.04 * dfrac * (1.0 - ring)
        for q in range(44):
            a = 2 * math.pi * q / 44
            sprite(G, cam, nx + r * math.cos(a) / 0.28125, ny + r * math.sin(a) / 0.5, sz, sz, (3.0, 2.4, 1.2), df, 0.4)


def wave_h(val):
    return min(0.22 * max(val, 1.0) ** 0.8, 2.4)


def beach_waves(F, val, t):
    """파란 상자 띠(높이 = 조석 배수) + 흰 거품 띠. 지후가 선 데크는 y<2.0이라 닿지 않음."""
