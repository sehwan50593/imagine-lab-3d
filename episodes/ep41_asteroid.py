def earth_rot(sp):
    return _rmat(math.radians(-23.4), 0.0, 0.0) @ _rmat(0.0, 0.0, sp)


def earth_items(F, BL, cam, sp, s_imp=None, nimp=None, patch=0.175):
    """지구: 파란 구(조명 받음) + 앞쪽 반구에 보이는 땅·극지 조각(자전 sp). 충돌 뒤(s_imp ≥ 0)엔 충돌점 둘레 땅이 먼지색으로 번지고 바다에도 탄 자국이 생김."""
    ox, oy = OFF["spaceB"]
    cw = np.array((ox, oy, 0.0))
    BL.orbw(cw, 2 * RE, OCEAN)
    view = cam["loc"] - cw
    view = view / np.linalg.norm(view)
    R = earth_rot(sp)
    phi = 0.0
    if s_imp is not None and s_imp >= 0.0:
        phi = 0.25 + 1.8 * ramp(s_imp, 0.2, 4.0)
    for k in (range(len(EARTH_PTS)) if phi > 0.0 else LAND_IDX):
        n = R @ EARTH_PTS[k]
        if n @ view < 0.04:
            continue
        col, land = (LAND_COL[k], True) if k in LAND_COL else (DUST, False)
        if phi > 0.0:
            ang = math.acos(max(-1.0, min(1.0, float(n @ nimp))))
            w = 0.9 * ramp(phi - ang, 0.0, 0.35)
            if not land and (w <= 0.0 or ang > 0.65):
                continue
            if w > 0.0:
                col = tuple(lerp(a_, b_, w) for a_, b_ in zip(col, DUST))
        F.cw(cw + n * (RE + 0.012), (0.05, patch, patch), col, rot_n(n))


