def dino_items(G, q, t, flash=0.0):
    """지구 꼭대기에 선 공룡 그림(주황빛 발광 상자). q 0 → 1 = 조용히 흩어져 사라짐."""
    ox, oy = OFF["spaceB"]
    up = DINO_N
    fwd = np.array((1.0, 0.0, 0.0)) - up * up[0]
    fwd = fwd / np.linalg.norm(fwd)
    left = np.cross(up, fwd)
    rot = euler_of(np.stack([fwd, left, up], 1))
    base = np.array((ox, oy, 0.0)) + up * (RE - 0.02)
    bob = 0.02 * math.sin(2 * math.pi * 1.1 * t)
    for n, (lc, sz) in enumerate(DINO):
        c = base + (fwd * lc[0] + left * lc[1] + up * (lc[2] + bob)) * DINO_S
        k = 1.0 - q
        if q > 0.0:
            dirn = fwd * (_h(n + 60) - 0.4) + left * (_h(n + 70) - 0.5) + up * (0.5 + _h(n + 80))
            c = c + dirn / np.linalg.norm(dirn) * (0.9 * q * (0.6 + _h(n + 90)))
            k = max(0.0, 1.0 - q) ** 0.7 * (0.75 + 0.25 * math.sin(14.0 * t + n))
        if k > 0.02:
            col = tuple((2.6 + 4.0 * flash, 1.7 + 3.0 * flash, 0.7 + 2.0 * flash)[m] for m in range(3))
            G.cw(c, tuple(v_ * DINO_S * k for v_ in sz), col, rot)


