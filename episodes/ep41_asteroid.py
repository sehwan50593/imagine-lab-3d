# 번쩍 (줄, 줄 시작 후 초, 세기, 길이 초) — STYLE='pixe'에선 overlay의 FLASH가 안 쓰여서 postfx에서 화면 전체에 얹음
FLASHES = [(LN["hook"], T_BURST, 0.80, 0.24), (LN["hook"], T_PANE, 0.30, 0.15), (LN["ring"], 0.0, 0.50, 0.30), (LN["shatter"], 0.52, 0.40, 0.20),
           (LN["chicx"], T_IMP, 0.62, 0.30), (LN["dart"], T_HIT, 0.55, 0.22)]
WARM = np.array((1.0, 0.95, 0.86), np.float32)
LUMA = np.array((0.2126, 0.7152, 0.0722), np.float32)
SEPIA = np.array((1.04, 0.97, 0.86), np.float32)


def flash_level(t):
    a = 0.0
    for i, tau0, peak, dur in FLASHES:
        t0 = shot_span(i)[0] + tau0
        a = max(a, peak * clamp((t - t0 + 0.02) / 0.03) * (1.0 - clamp((t - t0 - 0.01) / dur)))
    return a


def postfx(img, t):
    """번쩍(전체 화면) + 8번 줄(1908년 퉁구스카) 흑백 옛 사진 느낌: 채도를 거의 다 빼고 세피아 톤 (앞뒤 0.1초에 색이 빠지고 돌아옴)."""
    a0, b0 = shot_span(LN["tunguska"])
    w = ramp(t, a0 - 0.02, a0 + 0.10) * (1.0 - ramp(t, b0 - 0.10, b0 + 0.02))
    if w > 0.0:
        g = (img @ LUMA)[..., None]
        img = (img + (g - img) * np.float32(0.96 * w)) * (1.0 + (SEPIA - 1.0) * np.float32(w))
    a = flash_level(t)
    if a > 0.0:
        img = img + (WARM - img) * np.float32(a)
    return img


def frame_state(t):
    """t초의 장면 상태(블렌더 없이 계산): 사람·소품 점 배열, 카메라, 조명."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    dur = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = min(tau / dur, 1.0)
    cam = cam_pose(i, tau, u)
    S, P, R, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in W["C"]:
        d = state_of(c, i, u, tau, dur, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None or d["set"] != cam["set"]:
            P.append((0.0, 0.0, 0.0))
            R.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        S[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox, d["y"] + oy, d["z"]))
        R.append((0.0, 0.0, math.radians(d["yaw"])))
        SC.append(d["scale"])
        PO.append(W["PI"][(d["pose"], c["hair"], c["extra"])])
    F, G, OR, BL, LT = props(i, tau, dur, u, S, t, cam)
    return dict(i=i, tau=tau, u=u, set=cam["set"], cam=cam, A=S, P=P, R=R, CO=CO, C2=C2, SC=SC, PO=PO, F=F, G=G, OR=OR, BL=BL, LT=LT,
                env=env(i, tau))


