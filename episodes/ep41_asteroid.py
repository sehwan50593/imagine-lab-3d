def ground_ring(G, c, r, thick, col, z=0.7, n=120):
    """땅 위(높이 z)에 눕힌 고리: 가는 발광 상자 n개가 이어짐 (세트 좌표)."""
    a = [(c[0] + r * math.cos(2 * math.pi * q / n), c[1] + r * math.sin(2 * math.pi * q / n)) for q in range(n + 1)]
    L = 2 * math.pi * r / n * 1.06
    for q in range(n):
        mx, my = (a[q][0] + a[q + 1][0]) / 2, (a[q][1] + a[q + 1][1]) / 2
        G.c((mx, my, z), (L, thick, thick), col, (0.0, 0.0, math.atan2(a[q + 1][1] - a[q][1], a[q + 1][0] - a[q][0])))


