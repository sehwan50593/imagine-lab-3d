def rock_items(F, base, parts, spin, col=ROCK_D):
    Rs = _rmat(0.0, 0.0, spin)
    for p, sz, R, br in parts:
        F.cw(base + Rs @ p, sz, tuple(q * br for q in col), euler_of(Rs @ R))


def a_moon(t):
    """위성의 (각도, 궤도 반지름): DART가 부딪히기 전엔 일정, 부딪힌 뒤엔 궤도가 줄고 더 빨리 돎."""
    t14 = STARTS[LN["orbit"]]
    th = STARTS[LN["dart"]] + T_HIT
    if t < th:
        return TH0 + W0 * (t - t14), OR0
    d = t - th
