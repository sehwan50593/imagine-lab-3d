def _rock(n, rad, smin, smax, seed):
    """울퉁불퉁한 바위: 타원체 안쪽에 흩어 놓은 상자 n개 [(자리, 크기, 회전행렬, 밝기)]."""
    out = []
    for k in range(n):
        d = np.array((_h(seed + k) - 0.5, _h(seed + k + 40) - 0.5, _h(seed + k + 80) - 0.5))
        d = d / np.linalg.norm(d) * (0.45 + 0.5 * _h(seed + k + 120))
        sz = smin + (smax - smin) * _h(seed + k + 160)
        R = _rmat(6.28 * _h(seed + k + 200), 6.28 * _h(seed + k + 240), 6.28 * _h(seed + k + 280))
        out.append((d * np.array(rad), (sz, sz * (0.8 + 0.4 * _h(seed + k + 320)), sz * (0.8 + 0.4 * _h(seed + k + 360))), R,
                    0.85 + 0.3 * _h(seed + k + 400)))
    return out


