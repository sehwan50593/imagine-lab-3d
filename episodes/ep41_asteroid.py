def _rbox(v, cx, cy, z0, z1, L, W, yaw, col, jit=0.05):
    """방위각 yaw로 돌린 상자를 세트(Vox)에 박음 (위 면 + 옆 네 면). 쓰러진 나무용."""
    c, s = math.cos(yaw), math.sin(yaw)
    ex, ey = np.array((c, s)) * L / 2, np.array((-s, c)) * W / 2
    p = [np.array((cx, cy)) + ex * a + ey * b for a, b in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
    col = v._jit(col, jit) if jit else tuple(col)
    lo = [np.array((q[0], q[1], z0)) for q in p]
    hi = [np.array((q[0], q[1], z1)) for q in p]
    v._quad(v.solid, hi, col)
    for a, b, kk in ((0, 1, 0.9), (1, 2, 0.84), (2, 3, 0.9), (3, 0, 0.84)):
        v._quad(v.solid, [lo[a], lo[b], hi[b], hi[a]], tuple(min(1.0, q * kk) for q in col))


