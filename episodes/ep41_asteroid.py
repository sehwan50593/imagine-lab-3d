# 6번 줄(일 주일 뒤) 창 상태: 0 비어 있음 · 1 임시 비닐 · 2 새 유리  (보이는 가운데 네 칸 줄은 직접 정함, 나머지는 섞어서)
REPAIR_STATE = {(2, 0): 1, (3, 0): 1, (4, 0): 2, (5, 0): 1, (2, 1): 1, (3, 1): 0, (4, 1): 1, (5, 1): 2,
                (2, 2): 2, (3, 2): 2, (4, 2): 1, (5, 2): 0, (2, 3): 2, (3, 3): 2, (4, 3): 2, (5, 3): 1}
