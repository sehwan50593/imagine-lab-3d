def vanish_k(dv):
    """'퐁' 사라짐 크기(1 → 살짝 커짐 → 0): dv = 사라지는 순간 이후 초."""
    if dv <= 0.0:
        return 1.0
    if dv >= 0.16:
        return 0.0
    return (1.0 + 0.3 * math.sin(math.pi * min(dv / 0.06, 1.0))) * (1.0 - smooth((dv - 0.04) / 0.12))


def rel(d, fwd, lat, up):
    """캐릭터 기준 (앞, 왼쪽, 위) → 세트 좌표. 크기 반영."""
    a = math.radians(d["yaw"])
    s = d["scale"]
    return (d["x"] + s * (fwd * math.cos(a) - lat * math.sin(a)), d["y"] + s * (fwd * math.sin(a) + lat * math.cos(a)),
            d["z"] + s * up)


