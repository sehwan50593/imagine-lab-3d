def frame_state(t):
    """t초의 장면 상태(블렌더 없이 계산): 사람·소품 점 배열, 카메라, 조명."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    dur = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = min(tau / dur, 1.0)
    cam = cam_pose(i, u)
    S, P, R, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in W["C"]:
        d = state_of(c, i, u, tau, dur, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None:
            P.append((0.0, 0.0, 0.0))
            R.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        S[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox, d["y"] + oy, d["z"]))
        R.append((0.0, d["pitch"], math.radians(d["yaw"])))
        SC.append(d["scale"])
        PO.append(W["PI"][(d["pose"], c["hair"], c["extra"])])
    F, G, OR, LT = props(i, tau, dur, u, S, t, cam)
    return dict(i=i, tau=tau, u=u, set=cam["set"], cam=cam, A=S, P=P, R=R, CO=CO, C2=C2, SC=SC, PO=PO, F=F, G=G, OR=OR, LT=LT,
                env=env(i, tau))


# ───────────────────────── 번쩍 (화면 전체 효과) ─────────────────────────
# (줄, 줄 시작 후 초, 세기, 길이 초): 훅은 현수막이 '퐁' 사라지는 순간 번쩍, 15번 줄은 전구가 켜질 때 살짝
FLASHES = [(IX["hook"], HK_POP, 0.95, 0.30), (IX["twist"], 1.0, 0.25, 0.20)]


def flash_level(t):
    """STYLE='pixe'에선 overlay의 FLASH가 안 쓰여서 번쩍을 postfx에서 화면 전체에 얹음 (제목·자막은 그 위에 그려짐)."""
    lv = 0.0
    for i, tau0, peak, dur in FLASHES:
        d = t - (shot_span(i)[0] + tau0)
        lv = max(lv, peak * clamp((d + 0.01) / 0.03) * (1.0 - clamp((d - 0.03) / dur)))
    return lv


def postfx(img, t):
    f = flash_level(t)
    if f > 0.0:
        img = img + (np.array((1.0, 0.95, 0.85), np.float32) - img) * np.float32(f)
    return img


