def vtext(v, txt, face, plane, center, cz, cell, col, glow=True, depth=0.015, gap=1):
    """벽에 박는 도트 글자(세트용). face = 글자가 바라보는 쪽('-y','+y','-x','+x'), plane = 벽 면 좌표(그 축), center = 벽을 따라 가운데, cz = 세로 가운데."""
    rows = text_rows(txt, gap)
    nc, nr = len(rows[0]), len(rows)
    sgn = 1.0 if face in ("-y", "+x") else -1.0
    for r, row in enumerate(rows):
        c = 0
        while c < nc:
            if row[c] != "#":
                c += 1
                continue
            c1 = c
            while c1 + 1 < nc and row[c1 + 1] == "#":
                c1 += 1
            a0 = center + sgn * (c - 0.5 - (nc - 1) / 2) * cell
            a1 = center + sgn * (c1 + 0.5 - (nc - 1) / 2) * cell
            lo, hi = min(a0, a1), max(a0, a1)
            z1 = cz + ((nr - 1) / 2 - r + 0.5) * cell
            z0 = z1 - cell
            if face == "-y":
                v.box(lo, hi, plane - depth, plane, z0, z1, col, jit=0, glow=glow)
            elif face == "+y":
                v.box(lo, hi, plane, plane + depth, z0, z1, col, jit=0, glow=glow)
            elif face == "-x":
                v.box(plane - depth, plane, lo, hi, z0, z1, col, jit=0, glow=glow)
            else:
                v.box(plane, plane + depth, lo, hi, z0, z1, col, jit=0, glow=glow)
            c = c1 + 1


