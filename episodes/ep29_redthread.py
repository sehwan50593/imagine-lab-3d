def _rot_x(bm, ang, pivot):
    """pivot을 지나는 앞뒤축(x) 둘레로 회전 (팔을 옆으로 벌림)."""
    c, s = math.cos(ang), math.sin(ang)
    for vt in bm.verts:
        y, z = vt.co.y - pivot[1], vt.co.z - pivot[2]
        vt.co.y, vt.co.z = pivot[1] + c * y - s * z, pivot[2] + s * y + c * z
    return bm


def _p29(pose, hair, kind):
    """[(bmesh, 재질번호)] — voxel._person 몸에 팔 각도만 갈아 끼우고(새 자세), 노인(old)은 긴 수염·콧수염·도포를 더함."""
    from engine import bkit as K
    base, arms = CUSTOM.get(pose, (pose, None))
    P = X._person(X.POSES[base], bool(hair))
    hip = _hip(base)
    if arms is not None:
        for bm, _ in P[-4:]:
            bm.free()
        P = P[:-4]
        lat = arms[2:4] if len(arms) == 4 else (0.0, 0.0)
        for sy, ang, la in ((-0.34, arms[0], lat[0]), (0.34, arms[1], lat[1])):
            piv = (0, 0, hip + 0.54)
            for bm, m in ((K.bm_cube(0.18, 0.16, 0.46, (0, sy, hip + 0.12), bottom=True), 0),
                          (K.bm_cube(0.17, 0.15, 0.14, (0, sy, hip - 0.02), bottom=True), 2)):
                X._rot_y(bm, ang, piv)
                if la:
                    _rot_x(bm, la if sy > 0 else -la, (0, sy, hip + 0.54))
                P.append((bm, m))
    if kind == "old":
        hz = hip + 0.58
        P += [(K.bm_cube(0.08, 0.30, 0.55, (0.195, 0, hz - 0.55), bottom=True), 3),        # 긴 수염 (머리카락 재질 = 흰색)
              (K.bm_cube(0.03, 0.24, 0.045, (0.245, 0, hz + 0.075), bottom=True), 3),      # 콧수염
              (K.bm_cube(0.36, 0.56, 0.74, (0, 0, 0.06), bottom=True), 0)]                  # 도포 자락 (셔츠 색)
    return P


def _glow_mat(name, strength):
    """인스턴스 'col' 색으로 빛나는 재질 (ep26과 같은 방식)."""
    from engine import bkit as K
    m, nt, out = K.new_mat(name)
    e = nt.nodes.new("ShaderNodeEmission")
    K.ln(nt, K.inst_attr(nt, "col"), e.inputs["Color"])
    e.inputs["Strength"].default_value = strength
    K.ln(nt, e.outputs[0], out.inputs["Surface"])
    m.cycles.emission_sampling = "NONE"
    return m


