def cut_at(i, u):
    """줄 i의 지금 컷: (shot, 그 컷 안 진행도)."""
    cuts = LINES[i].get("cuts")
    if not cuts:
        return LINES[i]["shot"], u
    u0 = 0.0
    for ue, sh in cuts:
        if u <= ue or (ue, sh) == cuts[-1]:
            return sh, clamp((u - u0) / max(ue - u0, 1e-3))
        u0 = ue


def cam_pose(shot, u, S):
    """컷 진행도 u에서 카메라: (세트, 목표점, 방위각, 고도각, 거리, 렌즈, 위치) — 월드 좌표."""
    st_, tg, az, el, dist, lens, push, daz = shot[:8]
    if len(shot) > 8 and shot[8][0] in S:                       # 사람을 따라가는 컷
        d, off = S[shot[8][0]], shot[8][1]
        tg = (d["x"] + off[0], d["y"] + off[1], d["zs"] + off[2])
    o = OFF[st_]
    tgt = (tg[0] + o[0], tg[1] + o[1], tg[2])
    a, e, dd = az + daz * u, math.radians(el), dist * (1 + (push - 1) * u)
    loc = (tgt[0] + math.cos(e) * math.cos(math.radians(a)) * dd, tgt[1] + math.cos(e) * math.sin(math.radians(a)) * dd,
           tgt[2] + math.sin(e) * dd)
    return st_, tgt, a, el, dd, lens, loc


def frame_state(t):
    """t초의 장면 상태: 사람·실·하트 점 배열, 카메라, 빛."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    dur = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = tau / dur
    S, P, R, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in W["C"]:
        d = state_of(c, i, u, tau, dur, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None:
            P.append((0.0, 0.0, 0.0))
            R.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        S[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox, d["y"] + oy, d["z"]))
        R.append((0.0, d["tilt"], math.radians(d["yaw"])))
        SC.append(d["scale"])
        PO.append(W["PI"][(d["pose"], c["hair"], c["kind"])])
    shot, ul = cut_at(i, u)
    st_, tgt, az, el, dist, lens, loc = cam_pose(shot, ul, S)
    o = OFF[st_]
    TL = threads(i, u, tau, S)
    for T in TL:
        T["a"] = (T["a"][0] + o[0], T["a"][1] + o[1], T["a"][2])
        T["b"] = (T["b"][0] + o[0], T["b"][1] + o[1], T["b"][2])
    TP, TS, TZ, TR, TC, glows = thread_arrays(TL, t, loc)
    hs = hearts_spec(i, tau, S)
    if hs:
        hs = ((hs[0][0] + o[0], hs[0][1] + o[1], hs[0][2]), hs[1])
    HP, HS, HR = hearts_arrays(hs, t, tau, az)
    return dict(i=i, u=u, tau=tau, S=S, P=P, R=R, CO=CO, C2=C2, SC=SC, PO=PO, tgt=tgt, az=az, el=el, dist=dist,
                lens=lens, loc=loc, st=st_, env=env_of(i), TP=TP, TS=TS, TZ=TZ, TR=TR, TC=TC, glows=glows[:2],
                HP=HP, HS=HS, HR=HR)


