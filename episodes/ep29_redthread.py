def hearts_arrays(spec, t, tau, camaz):
    """하트 NH개: spec=(가운데 점, 시작 τ) → 떠오르며 커졌다 사라짐. 카메라를 보게 돌림. (pos, scale, rot)"""
    pos = np.zeros((NH, 3), np.float32)
    sc = np.zeros(NH, np.float32)
    rot = np.zeros((NH, 3), np.float32)
    if spec is None:
        return pos, sc, rot
    c, t0 = spec
    for k in range(NH):
        p = ((tau - t0) * 0.5 + k / NH) % 1.0
        on = 1.0 if tau >= t0 else 0.0
        pos[k] = (c[0] + 0.55 * math.sin(k * 2.399), c[1] + 0.25 * math.cos(k * 1.7), c[2] + 0.2 + 1.5 * p)
        sc[k] = 1.8 * on * (0.35 + 0.55 * ((k * 7) % 5) / 4) * ramp(p, 0.0, 0.15) * (1 - ramp(p, 0.65, 1.0))
        rot[k] = (0.0, 0.0, math.radians(camaz + 90.0))
    return pos, sc, rot


