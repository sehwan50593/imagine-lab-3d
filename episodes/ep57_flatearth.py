def arrow3(G, p0, p1, col, th=0.06, head=0.22):
    """p0에서 p1으로 향하는 블록 화살표(머리는 p1 쪽)."""
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    v = p1 - p0
