    ang = -t * 14.0 * d
    out = [bx(x, y, 0.20, 1.0, 0.28, 0.16, col), bx(x - 0.1 * d, y, 0.36, 0.55, 0.30, 0.10, (0.15, 0.15, 0.17)),
           bx(x + 0.42 * d, y, 0.36, 0.10, 0.50, 0.06, (0.2, 0.2, 0.22)),
           bx(x - 0.5 * d, y, 0.45, 0.42, 0.42, 0.42, (0.95, 0.95, 0.9)), bx(x - 0.5 * d, y, 0.52, 0.43, 0.43, 0.08, col)]
