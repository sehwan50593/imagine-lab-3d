def pixtext(text, cx, z0, y, cell, cols, depth=0.05, gap=1.0, scale=None):
    """5x7 도트 숫자 글 → 발광 상자 목록 (칠판용). cols = 글자별 색 목록, scale = 글자별 크기 배율(None이면 1)."""
    ws = [len(PF[ch][0]) for ch in text]
    total = sum(ws) + gap * (len(text) - 1)
    out = []
    x = cx - total * cell / 2
    for k, ch in enumerate(text):
        s = 1.0 if scale is None else scale[k]
        if s > 0:
            rows = [r.replace("1", "#").replace("0", ".") for r in PF[ch]]
            xm = x + ws[k] * cell / 2                       # 글자 가운데 · 바닥 가운데를 기준으로 크기 조절
            for r, c0, c1 in _runs(rows):
                zz = z0 + (6 - r) * cell
                out.append(((xm + ((c0 + c1 + 1) / 2 - ws[k] / 2) * cell * s, y, zz * s + z0 * (1 - s) + cell * s / 2),
                            ((c1 - c0 + 1) * cell * s, depth * s, cell * s), (0, 0, 0), cols[k]))
        x += (ws[k] + gap) * cell
    return out


def steam(x, y, z0, t, n=5, rise=0.55, size=0.075):
    """김: 하얀 작은 상자가 솟아 오르며 작아짐."""
    out = []
    for k in range(n):
        p = (k / n + t / 1.5) % 1.0
        s = size * (1 - 0.6 * p)
        out.append(((x + 0.06 * math.sin(6.3 * (p + k * 0.37)), y + 0.04 * math.cos(6.3 * (p + k * 0.21)), z0 + rise * p),
                    (s, s, s), (p * 3, k, p * 2), (0.97, 0.97, 0.98)))
    return out


def sparkles(c, tl, t0, n=14, r=0.9, life=0.9, cols=((1.0, 0.85, 0.3), (1.0, 0.6, 0.75), (1.0, 1.0, 0.9))):
    """c 둘러싸고 터져 나가는 발광 반짝이."""
    out = []
    tau = tl - t0
    if tau <= 0 or tau > life:
        return out
    f = tau / life
    for k in range(n):
        a = 2 * math.pi * k / n + 0.7 * (k % 3)
        rr = r * (0.35 + 0.65 * ((k * 5) % 7) / 6.0) * math.sqrt(f)
        s = 0.11 * (1 - f) * (1 + 0.5 * (k % 2))
        out.append(((c[0] + rr * math.cos(a), c[1] + 0.15 * math.sin(a * 2), c[2] + rr * math.sin(a) * 0.9 + 0.15),
                    (s, s, s), (a, f * 4, 0), cols[k % len(cols)]))
    return out


def motes(box, t, n=12, col=(1.0, 0.9, 0.6), size=0.03):
    """빛 속에 떠다니는 먼지: box = (x0, x1, y0, y1, z0, z1)."""
    out = []
    for k in range(n):
        q = ((k * 0.6180339) % 1.0, (k * 0.3819660 + 0.2) % 1.0, (k * 0.7548777 + 0.4) % 1.0)
        x = box[0] + (box[1] - box[0]) * q[0] + 0.08 * math.sin(0.9 * t + 6.3 * q[1])
        y = box[2] + (box[3] - box[2]) * q[1] + 0.06 * math.sin(0.7 * t + 6.3 * q[2])
        z = box[4] + (box[5] - box[4]) * ((q[2] - 0.05 * t) % 1.0)
        out.append(((x, y, z), (size, size, size), (k, 0.3 * k, 0), col))
    return out


