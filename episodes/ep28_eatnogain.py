def tower(x, y, z0, n, tl, seed, sway=0.02, grow=None):
    """접시 탑: 층마다 흰 접시 + 음식 한 점, 위로 갈수록 흔들림. grow=(처음 안 보이는 층, 첫 층 시각, 층 간격(초))이면
    그 위 층들이 차례로 위에서 떨어져 내려앉음."""
    rs = np.random.default_rng(seed)
    out = []
    for k in range(n):
        c = FOODS[int(rs.integers(len(FOODS)))]
        ox, oy = (float(q) for q in rs.uniform(-0.05, 0.05, 2))
        ang = float(rs.uniform(0, 3))
        dz = 0.0
        if grow and k >= grow[0]:
            tau = tl - (grow[1] + (k - grow[0]) * grow[2])
            if tau < 0:
                continue
            dz = 0.7 * max(0.0, 1 - tau / 0.2) ** 2
        f = (k / max(n - 1, 1)) ** 2
        dx = sway * f * math.sin(tl * 3.1 + seed)
        z = z0 + 0.10 * k + dz
        out.append(bx(x + dx, y, z, 0.28, 0.28, 0.03, PLATE))
        out.append(bx(x + dx + ox, y + oy, z + 0.03, 0.12, 0.10, 0.055, c, (0, 0, ang)))
    return out


