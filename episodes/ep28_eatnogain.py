def rod(p0, p1, th, col):
    """p0에서 p1까지 이은 가는 막대 (지시봉·거미줄·주둥이)."""
    dx, dy, dz = p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]
    return (((p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2, (p0[2] + p1[2]) / 2),
            (math.sqrt(dx * dx + dy * dy + dz * dz), th, th), (0.0, -math.atan2(dz, math.hypot(dx, dy)), math.atan2(dy, dx)), col)


