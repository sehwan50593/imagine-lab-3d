def heart(c, s, az, col):
    """픽셀 하트(발광 상자): c 가운데, s 한 칸 크기, 카메라(방위각 az)를 봄."""
    phi = math.radians(az + 90)
    cp, sp = math.cos(phi), math.sin(phi)
    out = []
    for r, c0, c1 in _runs(HEART):
        dx = ((c0 + c1 + 1) / 2 - 3.5) * s
        out.append(((c[0] + dx * cp, c[1] + dx * sp, c[2] + (2.5 - r) * s), ((c1 - c0 + 1) * s, s * 0.5, s), (0, 0, phi),
                    col if HEART[r][c0] == "R" else (1.0, 0.75, 0.8)))
    return out


def puffs(d, tl, n=3, life=1.1, size=0.08):
    """입에서 나와 앞쪽 아래로 흩어지는 하얀 한숨 상자."""
    mx, my, mz = mouth_pt(d)
    a = math.radians(d["yaw"])
    out = []
    for s in range(n):
        age = (tl + s * life / n) % life
        fwd = 0.05 + 0.55 * age
        sz = size * (1.0 - 0.5 * age / life) * d["scale"]
        out.append(((mx + math.cos(a) * fwd, my + math.sin(a) * fwd, mz - 0.25 * age), (sz, sz, sz),
                    (0.4 * s, 0.3 * s, 0.5 * s), (0.95, 0.96, 0.98)))
    return out


def cobweb(c, y, r0=0.15, n=3):
    """모서리 거미줄: c=(x, z) 모서리에서 아래·오른쪽 부채꼴로 뻗는 가는 막대."""
    angs = [0.0, -math.pi / 6, -math.pi / 3, -math.pi / 2]
    col = (0.9, 0.9, 0.93)
    pt = lambda r, a: (c[0] + r * math.cos(a), y, c[1] + r * math.sin(a))
    out = [rod(pt(0, 0), pt(r0 * n + 0.1, a), 0.008, col) for a in angs]
    for k in range(1, n + 1):
        for a0, a1 in zip(angs, angs[1:]):
            out.append(rod(pt(r0 * k, a0), pt(r0 * k, a1), 0.007, col))
    return out


