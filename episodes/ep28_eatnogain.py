def _lean_pt(lean, x, z):
    """서 있는 몸 좌표 (앞 x, 높이 z)의 머리 쪽 점이 허리 숙임(lean)으로 옮겨 간 자리."""
    c, s = math.cos(-lean * 0.6), math.sin(-lean * 0.6)
    dx, dz = x, z - 1.36
    x1, z1 = c * dx + s * dz, 1.36 + (-s * dx + c * dz)
    c, s = math.cos(lean), math.sin(lean)
    dx, dz = x1, z1 - 0.78
    return c * dx + s * dz, 0.78 - s * dx + c * dz


