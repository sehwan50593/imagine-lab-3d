# 번쩍 (줄, 줄 시작 후 초, 세기, 길이 초): 훅 끝에 눈이 돌아볼 때, 반전(16번) 사진이 켜질 때
def _flashes():
    a, b = shot_span(LN["hook"])
    return [(LN["hook"], _TURN + 0.2, 0.30, 0.18), (LN["twist"], 0.1, 0.22, 0.16)]


WARM = np.array((1.0, 0.95, 0.86), np.float32)


def flash_level(t):
    a = 0.0
    for i, tau0, peak, dur in _flashes():
        t0 = shot_span(i)[0] + tau0
        a = max(a, peak * clamp((t - t0 + 0.02) / 0.03) * (1.0 - clamp((t - t0 - 0.01) / dur)))
    return a


def postfx(img, t):
    """번쩍(전체 화면)."""
    a = flash_level(t)
    if a > 0.0:
        img = img + (WARM - img) * np.float32(a)
    return img


def frame_state(t):
    """t초의 장면 상태(블렌더 없이 계산): 사람·소품 점 배열, 카메라, 조명."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    dur = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = min(tau / dur, 1.0)
    cam = cam_pose(i, tau, u)
    S, P, R_, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in W["C"]:
        d = state_of(c, i, u, tau, dur, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None or d["set"] != cam["set"]:
            P.append((0.0, 0.0, 0.0))
            R_.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        S[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox, d["y"] + oy, d["z"]))
        R_.append((0.0, 0.0, math.radians(d["yaw"])))
        SC.append(d["scale"])
        PO.append(W["PI"][(d["pose"], c["hair"], c["extra"])])
    F, G, OR, BL, LT = props(i, tau, dur, u, S, t, cam)
    return dict(i=i, tau=tau, u=u, set=cam["set"], cam=cam, A=S, P=P, R=R_, CO=CO, C2=C2, SC=SC, PO=PO, F=F, G=G, OR=OR, BL=BL, LT=LT,
                env=env(i, cam["set"], u))


