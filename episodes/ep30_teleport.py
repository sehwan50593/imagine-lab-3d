def _lean_pt(lean, x, z, hip=0.78):
    """몸 좌표 (앞 x, 높이 z)의 머리 쪽 점이 허리 숙임(lean)으로 옮겨 간 자리."""
    hz = hip + 0.58
    c, s = math.cos(-lean * 0.6), math.sin(-lean * 0.6)
    dx, dz = x, z - hz
    x1, z1 = c * dx + s * dz, hz + (-s * dx + c * dz)
    c, s = math.cos(lean), math.sin(lean)
    dx, dz = x1, z1 - hip
    return c * dx + s * dz, hip - s * dx + c * dz


