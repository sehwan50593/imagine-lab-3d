def flash_glow(c, tau, kind):
    """번쩍 한 번의 발광 상자들. c = 몸 가운데, tau = 번쩍 시작 뒤 초. 'out'(사라짐): 큰 상자가 0.15초 만에 커졌다 사라지고,
    'in'(나타남): 큰 상자로 시작해 줄어듦. 둘 다 세로 빛기둥 · 바닥 파문 · 파편이 흩어짐."""
    G = []
    if tau < 0:
        return G
    x, y, z = c
    if kind == "out":
        s = 0.35 + 2.65 * (1 - (1 - tau / 0.15) ** 2) if tau < 0.15 else 3.0 * max(0.0, 1 - (tau - 0.15) / 0.08)
    else:
        s = 2.4 if tau < 0.05 else 2.4 * max(0.0, 1 - (tau - 0.05) / 0.15) ** 1.5
    if s > 0.01:
        G.append(((x, y, z), (s, s, s), (0.0, 0.0, 0.0), FL_COL))
        G.append(((x, y, z), (s, s, s), (0.0, 0.0, math.pi / 4), FL_COL))               # 45도 엇갈린 둘째 상자 = 뾰족한 별 모양
    if tau < 0.55:
        w = 0.04 + 0.5 * (1 - tau / 0.55) ** 1.5
        G.append(((x, y, 1.95), (w, w, 3.9), (0.0, 0.0, 0.0), (1.1, 1.3, 1.8)))        # 세로 빛기둥
    if tau < 0.5:
        f = tau / 0.5
        r = 0.25 + 3.0 * (1 - (1 - f) ** 2)
        for k in range(NRING):
            a = 2 * math.pi * k / NRING
            G.append(((x + r * math.cos(a), y + r * math.sin(a), 0.05), (0.30, 0.07 * (1 - f) + 0.01, 0.07 * (1 - f) + 0.01),
                      (0.0, 0.0, a + math.pi / 2), (0.7, 1.5, 2.1)))                        # 바닥 파문
    for k in range(NSH):
        life = SH_L[k]
        if tau >= life:
            continue
        v = SH_V[k] * (1 - math.exp(-3.5 * tau)) / 3.5
        ce = math.cos(SH_EL[k])
        s = SH_S[k] * (1 - tau / life) ** 0.6
        G.append(((x + math.cos(SH_AZ[k]) * ce * v, y + math.sin(SH_AZ[k]) * ce * v,
                   max(z + 0.25 + math.sin(SH_EL[k]) * v - 1.4 * tau * tau, 0.05)),
                  (s, s, s), (SH_AZ[k] + 3 * tau, SH_EL[k] + 5 * tau, 0.0), SHARD_COLS[k % 4]))
    return G


