def flash_level(t):
    """전체 화면 번쩍 세기 0~1 (번쩍 직전 0.05초에 확 올라 0.3초 동안 사그라듦)."""
    a = 0.0
    for tc, k in FLASH_ABS:
        d = t - tc
        if -0.05 < d < 0.32:
            a = max(a, k * (1 + d / 0.05) if d < 0 else k * (1 - d / 0.32) ** 2)
    return a


def postfx(img, t):
    """STYLE='pixe'에선 overlay의 FLASH 목록이 안 쓰여서(overlay._pixe) 번쩍을 여기서 화면 전체에 얹음 (제목·자막은 그 위에 그려짐)."""
    a = flash_level(t)
