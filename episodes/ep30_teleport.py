def cam_pose(shot, u, shake=(0.0, 0.0, 0.0)):
    """컷 진행도 u에서 카메라: (목표점, 방위각, 고도각, 거리, 렌즈, 위치) — 월드 좌표. CamRig.set과 같은 규칙."""
