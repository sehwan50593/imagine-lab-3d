        P.append((K.bm_cube((x1 - x0) * C0, (y1 - y0) * C0, (z1 - z0) * C0,
                            ((x0 + x1) / 2 * C0, (y0 + y1) / 2 * C0, z0 * C0), bottom=True), mi))
