def at(st, x, y, yaw, pose, z=0.0, **kw):
    return dict(set=st, x=x, y=y, yaw=yaw, pose=pose, z=z, **kw)


def alt(st, x, y, yaw, poses, period, z=0.0, ph=0.0, **kw):
    """같은 자리에서 자세를 period초마다 번갈아 (먹기·졸기 등)."""
    def fn(tl, du, u, t):
        return at(st, x, y, yaw, poses[int((t + ph) / period) % len(poses)], z, **kw)
    return fn


def mover(keys, st, step=0.3, walk=("walk_a", "walk_b"), end="stand", face=None, z=0.0, bob=0.02):
    """keys = [(줄 안 시각, x, y), ...]를 직선으로 이으며 걷는 함수. 걷는 동안엔 step초마다 발걸음 자세를 바꾸고,
    멈추면 end 자세로 face 방향(없으면 마지막으로 가던 방향)을 본다."""
    segs = [(a, b) for a, b in zip(keys, keys[1:]) if abs(b[1] - a[1]) + abs(b[2] - a[2]) > 1e-6]

    def fn(tl, du, u, t):
        head = math.degrees(math.atan2(segs[0][1][2] - segs[0][0][2], segs[0][1][1] - segs[0][0][1]))
        for a, b in segs:
            if a[0] < tl:
                head = math.degrees(math.atan2(b[2] - a[2], b[1] - a[1]))
        x, y, moving = keys[-1][1], keys[-1][2], False
        if tl <= keys[0][0]:
            x, y = keys[0][1], keys[0][2]
        elif tl < keys[-1][0]:
            for a, b in zip(keys, keys[1:]):
                if a[0] <= tl < b[0]:
                    k = (tl - a[0]) / (b[0] - a[0])
                    x, y = a[1] + (b[1] - a[1]) * k, a[2] + (b[2] - a[2]) * k
                    moving = abs(b[1] - a[1]) + abs(b[2] - a[2]) > 1e-6
        if moving:
            return at(st, x, y, head, walk[int(tl / step) % 2], z + bob * abs(math.sin(math.pi * tl / step)))
        return at(st, x, y, head if face is None else face, end, z)
    return fn


def walker(st, y, x0, vx, z=0.12, step=0.3, wrap=18.0):
    """거리를 x방향으로 걸어 지나가는 사람 (끝에 닿으면 반대편에서 다시)."""
    def fn(tl, du, u, t):
        x = (x0 + vx * t + wrap) % (2 * wrap) - wrap
        return at(st, x, y, 0.0 if vx > 0 else 180.0, ("walk_a", "walk_b")[int(t / step) % 2],
                  z + 0.02 * abs(math.sin(math.pi * t / step)))
    return fn


def _st(base, tl, du, u, t):
    return dict(base(tl, du, u, t)) if callable(base) else dict(base)


def react(base, t0, away=(0.0, 0.0), pose="shock", hop=0.10, lean=0.0, face=None):
    """줄 안 시각 t0에 깜짝 놀람: 자세가 pose로 바뀌고, 톡 튀어 오르며(hop) away만큼 물러나고 몸이 lean(rad, 음수 = 뒤로)만큼 기운다."""
    def fn(tl, du, u, t):
        d = _st(base, tl, du, u, t)
        tau = tl - t0
        if tau > 0:
            k = pop(tau, 0.26, 1.7)
            d["x"] += away[0] * k
            d["y"] += away[1] * k
            d["z"] = d.get("z", 0.0) + hop * math.sin(math.pi * min(tau / 0.32, 1.0))
            d["pose"] = pose
            d["tilt"] = lean * min(tau / 0.2, 1.0)
            if face is not None:
                d["yaw"] = face
        return d
    return fn


def hide_after(base, t_hide):
    """줄 안 시각 t_hide부터 안 보임 (번쩍하고 사라지는 쪽)."""
    def fn(tl, du, u, t):
        d = _st(base, tl, du, u, t)
        d["hide"] = tl >= t_hide
        return d
    return fn


def show_from(base, t_show):
    """줄 안 시각 t_show부터 보임 (번쩍하고 나타나는 쪽)."""
    def fn(tl, du, u, t):
        d = _st(base, tl, du, u, t)
        d["hide"] = tl < t_show
        return d
    return fn


def switch(*parts):
    """(시작 τ, 상태 또는 함수)를 이어 붙임 — 줄 안에서 시간에 따라 다른 동작."""
    def fn(tl, du, u, t):
        cur = parts[0][1]
        for t0, st in parts:
            if tl >= t0:
                cur = st
        return _st(cur, tl, du, u, t)
    return fn


