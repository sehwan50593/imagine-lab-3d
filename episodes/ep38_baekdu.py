def plane_model(F, G, OR, p, pitch, yaw, lit, T):
    """상자로 만든 여객기(몸통 6.4m, +x가 앞). lit[n] = 엔진 n의 불(0~1). 꺼진 엔진은 검은 연기 덩이를 흘림."""
    R0 = _rmat(0.0, pitch, yaw)

    def box(c, size, col, sweep=0.0):
        M = R0 @ _rmat(0.0, 0.0, sweep)
        F.c(np.asarray(p) + R0 @ np.asarray(c), size, col, euler_of(M))
    white, grey = (0.95, 0.95, 0.97), (0.62, 0.64, 0.70)
    box((0.0, 0.0, 0.0), (6.4, 0.8, 0.8), white)
    box((3.5, 0.0, -0.05), (0.9, 0.62, 0.62), white)
