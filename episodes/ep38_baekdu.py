def wall_trace(G, ox, tau, spike, pen):
    """벽 모니터의 지진 선: 가로 -1.8~1.8, 세로 가운데 z=2.0. spike = 큰 봉우리를 넣을지, pen = 그린 만큼(0~1)."""
    n = 72
    pts = []
    for k in range(n + 1):
        s = k / n
        if spike:
            e = 0.78 * math.exp(-((0.40 - s) / 0.035) ** 2) if s < 0.40 else 0.78 * math.exp(-(s - 0.40) / 0.10)
        else:
            e = 0.0
        w = (0.035 + e) * math.sin(2 * math.pi * 26.0 * s) + 0.02 * math.sin(2 * math.pi * 61.0 * s + 1.0)
        pts.append((s, ox - 1.8 + 3.6 * s, WALL_Y, 2.55 + w, e))
    for a, b in zip(pts, pts[1:]):
        if b[0] > pen:
            break
        d = np.array((b[1] - a[1], 0.0, b[3] - a[3]))
        ln = float(np.linalg.norm(d))
        hot = clamp(a[4] / 0.5)
        G.o((a[1], a[2], a[3]), (ln * 1.15, 0.02, 0.04), (0.3 + 3.0 * hot, 2.2 - 1.6 * hot, 0.6 - 0.3 * hot), rot_to(d / ln))
