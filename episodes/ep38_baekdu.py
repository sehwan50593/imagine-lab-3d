def euler_of(M):
    """회전행렬 M = Rz·Ry·Rx 의 (rx, ry, rz)."""
    return (math.atan2(M[2, 1], M[2, 2]), -math.asin(max(-1.0, min(1.0, float(M[2, 0])))), math.atan2(M[1, 0], M[0, 0]))


