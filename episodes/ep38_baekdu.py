def wave_h(x, y, T, amp):
    """호수 (x, y)의 물결 높이(m): 가운데에서 번지는 둥근 물결 + 잔물결."""
    r = math.hypot(x - MC[0], y - MC[1])
    return amp * (0.24 * math.sin(2 * math.pi * (0.8 * T - r / 5.0)) * math.exp(-r / 16.0) + 0.09 * math.sin(2 * math.pi * 2.3 * T + 1.1 * x + 1.4 * y))


def lake_plates(F, T, amp):
    n = 18
    cell = (2 * LH - 0.04) / n
