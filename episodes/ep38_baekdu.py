    box((-2.8, 0.0, 0.85), (1.0, 0.12, 1.1), (0.80, 0.15, 0.15))
    box((-2.9, 0.0, 0.38), (0.8, 2.2, 0.10), grey)
    box((-0.1, 1.7, -0.12), (1.7, 3.2, 0.12), grey, 0.45)
    box((-0.1, -1.7, -0.12), (1.7, 3.2, 0.12), grey, -0.45)
    for n, ey in enumerate(ENG_Y):
        ex = 0.30 - 0.25 * abs(ey)
        box((ex, ey, -0.40), (0.95, 0.34, 0.34), (0.40, 0.42, 0.48))
        rear = np.asarray(p) + R0 @ np.asarray((ex - 0.55, ey, -0.40))
