            w = wave_h(x, y, T, amp)
            top = LZ_WATER + w
            f = 1.0 + 0.9 * w + 0.04 * (_h(a * 13 + b) - 0.5)
            F.c((x, y, (LZ_BED + top) / 2), (cell - 0.02, cell - 0.02, top - LZ_BED), (0.10 * f, 0.40 * f, 0.88 * min(f, 1.25)))


