def _ring_rows(n, r0, r1, slash=True):
    """n x n 도트 원(바깥 r1·안쪽 r0) + 왼쪽 위 → 오른쪽 아래 사선 (금지 표지)."""
    c = (n - 1) / 2.0
    out = []
    for y in range(n):
        row = ""
        for x in range(n):
            r = math.hypot(x - c, y - c)
            on = r0 <= r <= r1 or (slash and r <= r1 and abs((x - c) - (y - c)) <= 0.9)
            row += "#" if on else "."
        out.append(row)
    return out


