def frame_state(t):
    """t초의 장면 상태(블렌더 없이 계산): 사람·소품 점 배열, 카메라, 조명, 세트 흔들림."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    dur = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = min(tau / dur, 1.0)
    cam = cam_pose(i, u, t)
    D = cam["shk"]
    S, P, R, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in W["C"]:
        d = state_of(c, i, u, tau, dur, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None:
            P.append((0.0, 0.0, 0.0))
            R.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        S[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox + D[0], d["y"] + oy + D[1], d["z"] + D[2]))
        R.append((0.0, d["pitch"], math.radians(d["yaw"])))
        SC.append(d["scale"])
        PO.append(W["PI"][(d["pose"], c["hair"], c["extra"])])
    F, G, OR, LT = props(i, tau, dur, u, S, t, cam)
    return dict(i=i, tau=tau, u=u, set=cam["set"], cam=cam, A=S, P=P, R=R, CO=CO, C2=C2, SC=SC, PO=PO, F=F, G=G, OR=OR, LT=LT,
                D=D, env=env(i, tau))


# ───────────────────────── 번쩍 · 흑백 (화면 전체 효과) ─────────────────────────
# (줄, 줄 시작 후 초, 세기, 길이 초): 훅은 0.1초에 쾅 하고 세게, 4번 줄 분출·훅 중간 번개는 약하게
FLASHES = [(IX["hook"], 0.10, 0.95, 0.30), (IX["hook"], 1.60, 0.22, 0.18), (IX["blast"], 0.08, 0.50, 0.26)]


def flash_level(t):
    """STYLE='pixe'에선 overlay의 FLASH가 안 쓰여서 번쩍을 postfx에서 화면 전체에 얹음 (제목·자막은 그 위에 그려짐)."""
    lv = 0.0
    for i, tau0, peak, dur in FLASHES:
        d = t - (shot_span(i)[0] + tau0)
        lv = max(lv, peak * clamp((d + 0.01) / 0.03) * (1.0 - clamp((d - 0.03) / dur)))
    return lv


def gray_level(t):
    """18번 줄(옛 연도판)은 흑백 톤: 줄 앞뒤 0.1초에 걸쳐 색이 빠짐."""
    a, b = shot_span(IX["year"])
    return 0.97 * smooth((t - a + 0.05) / 0.12) * smooth((b - t + 0.05) / 0.12)


def postfx(img, t):
    f = flash_level(t)
    if f > 0.0:
        img = img + (np.array((1.0, 0.93, 0.80), np.float32) - img) * np.float32(f)
    g = gray_level(t)
    if g > 0.0:
        lum = (img[..., 0:1] * 0.299 + img[..., 1:2] * 0.587 + img[..., 2:3] * 0.114)
        img = img + (np.repeat(lum, 3, axis=2) - img) * np.float32(g)
    return img


