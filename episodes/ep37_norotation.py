DAY = dict(sun=3.0, sun_col=(1.0, 0.92, 0.8), sun_rot=(50, 0, 35), amb=0.42, amb_col=(0.62, 0.68, 0.82), lt={})


def env(i, tau, st, t):
    """세트별 햇빛·주변광·켜 둘 점광원(이름: 세기)."""
    if st in ("river", "shore"):
        return DAY
    if st == "study":
        return dict(DAY, sun=2.2, amb=0.40, lt={"ep37_st_lamp": 45.0, "ep37_st_ceil": 120.0})
    if st == "plain":
        return dict(DAY, sun=4.4, sun_rot=(60, 0, 78 + 90), amb=0.46, lt={"ep37_pl_fill": 240.0})
    if st == "night":
        lt = {"ep37_ng%d" % n: 520.0 * (0.88 + 0.12 * math.sin(2 * math.pi * (0.8 + 0.17 * n) * t + n)) for n in range(6)}
        return dict(sun=0.35, sun_col=(0.55, 0.65, 1.0), sun_rot=(55, 0, 200), amb=0.16, amb_col=(0.34, 0.42, 0.70), lt=lt)
    if st == "camp":
        return dict(sun=2.8, sun_col=(1.0, 0.60, 0.34), sun_rot=(84, 0, CAMP_SUN_AZ + 90), amb=0.34, amb_col=(0.80, 0.62, 0.74),
                    lt={"ep37_cp_fire": 190.0 * (1.0 + 0.12 * math.sin(23.0 * t) * math.sin(7.3 * t)), "ep37_cp_fill": 90.0})
    return dict(DAY, sun=3.2, amb=0.44)


def frame_state(t):
    """t초의 장면 상태(블렌더 없이 계산): 사람·소품 점 배열, 카메라, 조명."""
    W = _world()
    i = line_at(t)
    a, b = shot_span(i)
    du = max(b - a, 1e-3)
    tau = max(t - a, 0.0)             # 줄 시작 0.02초 전부터 그 줄로 치므로 음수 방지
    u = min(tau / du, 1.0)
    cam = cam_pose(i, tau, u)
    A, P, R, CO, C2, SC, PO = {}, [], [], [], [], [], []
    for c in CAST:
        d = c["fn"](i, tau, du, u, t)
        CO.append(c["shirt"])
        C2.append(c["pants"])
        if d is None or d["set"] != cam["set"]:
            P.append((0.0, 0.0, 0.0))
            R.append((0.0, 0.0, 0.0))
            SC.append(0.0)
            PO.append(0)
            continue
        A[c["name"]] = d
        ox, oy = OFF[d["set"]]
        P.append((d["x"] + ox, d["y"] + oy, d["z"]))
        R.append((d["rx"], d["ry"], math.radians(d["yaw"])))
        SC.append(1.0)
        PO.append(W["PI"][(d["pose"], c["hair"], c["extra"])])
    F, G, OR, LT = Items(N_FX), Items(N_GL), Items(N_OR), []
    PROPS[cam["set"]](i, tau, du, u, A, t, cam, F, G, OR, LT)
    return dict(i=i, tau=tau, u=u, set=cam["set"], cam=cam, A=A, P=P, R=R, CO=CO, C2=C2, SC=SC, PO=PO, F=F, G=G, OR=OR, LT=LT,
                env=env(i, tau, cam["set"], t))


