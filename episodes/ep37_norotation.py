def hang(G, h, rx, ry, yaw_deg):
    """손 위치 h(몸 기준)가 점 G에 계속 닿도록 하는 발 위치 (회전 rx, ry, yaw)."""
    return np.asarray(G, float) - _rmat(rx, ry, math.radians(yaw_deg)) @ np.asarray(h, float)


