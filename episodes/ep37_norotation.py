def cam_pose(i, tau, u):
    """줄 i, 줄 시작 후 τ초(진행도 u)의 카메라: dict(set, cut, tgt, az, el, dist, lens, loc, shift, fwd, right, up) — 월드 좌표. CamRig.set과 같은 규칙."""
    shot, k, ul = cut_at(i, u)
    st_, tg, az, el, dist, lens, push, daz = shot[:8]
    shift = shot[8] if len(shot) > 8 else 0.0
    if LINES[i].get("ease") == "out":
        ul = 1.0 - (1.0 - ul) ** 2
    o = OFF[st_]
    tr = TRACK.get((i, k))
    base = tr(tau) if tr else (tuple(lerp(a_, b_, smooth(ul)) for a_, b_ in zip(tg, shot[9])) if len(shot) > 9 else tg)
    sx, sy, sz = shake(i, tau)
    tgt = np.array((base[0] + o[0] + sx, base[1] + o[1] + sy, base[2] + sz), float)
    a, e, dd = az + daz * ul, math.radians(el), dist * (1 + (push - 1) * ul)
    loc = tgt + np.array((math.cos(e) * math.cos(math.radians(a)), math.cos(e) * math.sin(math.radians(a)), math.sin(e))) * dd
    fwd = tgt - loc
    fwd /= np.linalg.norm(fwd)
    right = np.cross(fwd, (0.0, 0.0, 1.0))
    right /= np.linalg.norm(right)
    up = np.cross(right, fwd)
    return dict(set=st_, cut=k, tgt=tgt, az=a, el=el, dist=dd, lens=lens, loc=loc, shift=shift, fwd=fwd, right=right, up=up)


def project(cam, p):
    """월드 점 → (화면 x 0~1 왼쪽부터, y 0~1 위부터, 깊이). CamRig(센서 세로 24mm) + 렌즈 세로 이동(shift)과 같은 규칙."""
    d = np.asarray(p, float) - cam["loc"]
    z = float(d @ cam["fwd"])
    k = cam["lens"] / 24.0
    return 0.5 + (float(d @ cam["right"]) / z) * k / (1080.0 / 1920.0), 0.5 - (float(d @ cam["up"]) / z) * k + cam["shift"], z


