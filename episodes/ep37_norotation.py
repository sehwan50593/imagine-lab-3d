def _rmat(rx, ry, rz):
    cx, sx, cy, sy, cz, sz = math.cos(rx), math.sin(rx), math.cos(ry), math.sin(ry), math.cos(rz), math.sin(rz)
    return (np.array([[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]) @ np.array([[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]) @
            np.array([[1, 0, 0], [0, cx, -sx], [0, sx, cx]]))


class Items:
    """상자 인스턴스 모음. 상자 원점 = 뒷면 가운데, +x로 뻗음(size로 늘림). c()는 가운데 기준으로 넣음. 구는 orb(원점 = 가운데, size = 지름)."""

    def __init__(self, cap):
        self.cap, self.P, self.S, self.R, self.C = cap, [], [], [], []

    def o(self, origin, size, col, rot=(0.0, 0.0, 0.0)):
        self.P.append(tuple(float(q) for q in origin))
        self.S.append(tuple(float(q) for q in size))
        self.R.append(tuple(float(q) for q in rot))
        self.C.append(tuple(float(q) for q in col))

    def c(self, center, size, col, rot=(0.0, 0.0, 0.0)):
        org = np.asarray(center, float) - _rmat(*rot) @ np.array((size[0] / 2, 0.0, 0.0))
        self.o(org, size, col, rot)

    def orb(self, center, d, col):
        self.o(center, (d, d, d), col)

    def rig(self, pivot, rot, parts):
        """한 덩어리로 도는 물체: parts = [(피벗 기준 가운데, 크기, 색)] 전부 같은 회전 rot(오일러 x·y·z)을 받음."""
        R = _rmat(*rot)
        pv = np.asarray(pivot, float)
        for lc, size, col in parts:
            self.c(pv + R @ np.asarray(lc, float), size, col, rot)

    def __len__(self):
        return len(self.P)

    def arrays(self):
        n = len(self.P)
        assert n <= self.cap, f"인스턴스 칸 부족: {n} > {self.cap}"
        pad = self.cap - n
        z3 = [(0.0, 0.0, 0.0)] * pad
        return (np.array(self.P + z3, np.float32), np.array([1.0] * n + [0.0] * pad, np.float32),
                np.array(self.S + z3, np.float32), np.array(self.R + z3, np.float32), np.array(self.C + z3, np.float32))


def rot_cam(cam):
    """카메라 화면과 나란한 납작한 판의 오일러 회전: 상자 x = 앞(두께), y = 화면 가로, z = 화면 세로."""
    R = np.stack([cam["fwd"], -cam["right"], cam["up"]], 1)
    ry = -math.asin(max(-1.0, min(1.0, float(R[2, 0]))))
    return (math.atan2(float(R[2, 1]), float(R[2, 2])), ry, math.atan2(float(R[1, 0]), float(R[0, 0])))


def rot_to(d):
    """상자의 +x 축이 방향 d(단위벡터)를 향하게 하는 오일러 회전."""
    return (0.0, -math.asin(max(-1.0, min(1.0, float(d[2])))), math.atan2(float(d[1]), float(d[0])))


def screen_dir(cam, nx, ny):
    """화면 좌표 (nx 오른쪽 +, ny 위 +, 둘 다 -1~1)가 가리키는 방향 단위벡터."""
    f = cam["lens"]
    d = cam["fwd"] + nx * (6.75 / f) * cam["right"] + (ny + 2.0 * cam["shift"]) * (12.0 / f) * cam["up"]
    return d / np.linalg.norm(d)


def sprite(G, cam, nx, ny, w, h, col, dist=2.0, thick=0.02):
    """화면 좌표에 정면을 보는 납작한 상자를 카메라에서 dist m 앞에 둠. w·h = 화면 높이에 대한 비율. (가까이 두어 건물 뒤로 가려지지 않음)"""
    s = dist * 24.0 / cam["lens"]
    G.c(cam["loc"] + screen_dir(cam, nx, ny) * dist, (thick, w * s, h * s), col, rot_cam(cam))


def sprite_orb(OR, cam, nx, ny, dfrac, col, dist=2.0):
    """화면 좌표에 구를 둠 (dfrac = 화면 높이에 대한 지름 비율)."""
    OR.orb(cam["loc"] + screen_dir(cam, nx, ny) * dist, dfrac * dist * 24.0 / cam["lens"], col)


def sprite_line(G, cam, p0, p1, n, sz, col, dist=2.0):
    """화면 좌표 p0=(nx, ny) → p1을 점 n개로 잇는 점선. sz = 점 한 변(화면 높이 비율)."""
    for k in range(n):
        f = k / max(n - 1, 1)
        sprite(G, cam, p0[0] + (p1[0] - p0[0]) * f, p0[1] + (p1[1] - p0[1]) * f, sz, sz, col, dist, 0.012)


def _to_s(p):
    """화면 좌표 (nx, ny) → 화면 높이 단위 (가로 nx 1 = 0.28125, 세로 ny 1 = 0.5)."""
    return p[0] * 0.28125, p[1] * 0.5


def _from_s(q):
    return q[0] / 0.28125, q[1] / 0.5


def sprite_arrow(G, cam, p0, p1, col, n=7, sz=0.011, head=0.026, wing=0.030, dist=2.0):
    """p0 → p1 점선 화살표 (머리 = 큰 점 하나 + 양쪽 날개 점)."""
    sprite_line(G, cam, p0, p1, n, sz, col, dist)
    a, b = _to_s(p0), _to_s(p1)
    L = math.hypot(b[0] - a[0], b[1] - a[1]) or 1.0
    ux, uy = (b[0] - a[0]) / L, (b[1] - a[1]) / L
    for sgn in (-1, 1):                                                      # 머리 두 날개 (±145도)
        ang = math.radians(145 * sgn)
        wx, wy = ux * math.cos(ang) - uy * math.sin(ang), ux * math.sin(ang) + uy * math.cos(ang)
        for m in (1, 2):
            q = _from_s((b[0] + wx * wing * m * 0.6, b[1] + wy * wing * m * 0.6))
            sprite(G, cam, q[0], q[1], sz * 1.2, sz * 1.2, col, dist, 0.012)
    sprite(G, cam, p1[0], p1[1], head, head, col, dist, 0.012)


def pop(tau, dur=0.30, over=3.0):
    """톡 튀어나오는 크기: 0 → 살짝 커졌다 → 1 (easeOutBack). tau<0이면 0."""
    if tau <= 0:
        return 0.0
    if tau >= dur:
        return 1.0
    x = tau / dur - 1.0
    return 1.0 + (over + 1.0) * x ** 3 + over * x ** 2


