def pool_items(F, area, w):
    """바람 w초째의 해당 구역 물체들을 F에 넣음 (w < 0이면 제자리, 잔해는 안 보임)."""
    wrap = area == "C"
    for o in _POOL:
        if o["area"] != area:
            continue
        if o["kind"] == "debris":
            if w <= o["delay"]:
                continue
            k = ramp(w - o["delay"], 0.0, 0.25)
            parts = [(lc, tuple(q * k for q in sz), col) for lc, sz, col in o["parts"]]
        else:
            parts = o["parts"]
        (dx, dy, dz), rot = flight(o, w)
        hx, hy, hz = o["home"]
        F.rig((wrap_x(hx + dx, wrap), hy + dy, hz + dz), rot, parts)


