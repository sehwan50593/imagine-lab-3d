def person_fly(o, w, wrap):
    """사람이 바람에 날려 몸 가운데(높이 0.95m)를 중심으로 굴러 감: (발 위치, 오일러). 오일러 z에 서 있던 방향(−90도)을 포함."""
    (dx, dy, dz), (rx, ry, rz) = flight(o, w)
    rot = (rx, ry, rz - math.pi / 2)
    c = np.array((wrap_x(o["home"][0] + dx, wrap), o["home"][1] + dy, 0.95 + dz))
    p = c - _rmat(*rot) @ np.array((0.0, 0.0, 0.95))
    return p, rot


