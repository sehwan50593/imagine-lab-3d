def shake(i, tau):
    out = [0.0, 0.0, 0.0]
    for t0, dur, amp, hz, kind in _shake_spec(i):
        if tau < t0:
            continue
        if kind == "hit":
            k = (1.0 - clamp((tau - t0) / dur)) ** 2
        elif kind == "ramp":
            k = ramp(tau, t0, t0 + 1.5)
        else:
            k = 1.0 - 0.45 * clamp((tau - t0) / 4.0)
        w = 2 * math.pi * hz
        out[0] += amp * k * math.sin(w * tau + 1.3)
        out[1] += 0.5 * amp * k * math.sin(w * 0.83 * tau + 0.4)
        out[2] += amp * k * math.sin(w * 1.21 * tau + 2.1)
    return out


