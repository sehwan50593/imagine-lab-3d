# ── 천막촌: 모닥불, 해가 지평선에 걸림, 서윤의 밭과 괭이
def hoe_items(F, sy, up):
    """서윤이 밭을 일구는 괭이: 두 손 가운데에서 땅(내리칠 때)이나 머리 위(들 때)까지 자루 + 날."""
    pose = sy["pose"]
    R = _rmat(sy["rx"], sy["ry"], math.radians(sy["yaw"]))
    o = np.array((sy["x"], sy["y"], sy["z"]))
    hl = 0.5 * (np.array(hand_loc(pose, "R")) + np.array(hand_loc(pose, "L")))
    grip = o + R @ hl
    tip = o + R @ (np.array((1.05, 0.0, 0.05)) if not up else np.array((0.55, 0.0, 2.15)))
    back = grip + (grip - tip) * 0.30
    d = tip - back
    L_ = float(np.linalg.norm(d))
    F.c((back + tip) / 2, (L_, 0.06, 0.06), (0.50, 0.34, 0.20), rot_to(d / L_))
    F.c(tip + R @ np.array((0.05, 0.0, -0.02 if not up else 0.10)), (0.12, 0.30, 0.05), (0.40, 0.42, 0.46), (0.0, 0.0, math.radians(sy["yaw"])))


