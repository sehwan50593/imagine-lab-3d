def jd(y, m, d, h=0.0):
    if m <= 2:
        y, m = y - 1, m + 12
    a = y // 100
    b = 2 - a + a // 4
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + h / 24 + b - 1524.5


def helio(name, when_jd):
    """일심 황도 좌표 (AU)."""
    (a0, e0, i0, l0, w0, n0), (da, de, di, dl, dw, dn) = ELEMENTS[name]
    T = (when_jd - 2451545.0) / 36525.0
    a, e, I = a0 + da * T, e0 + de * T, math.radians(i0 + di * T)
    L, wbar, node = l0 + dl * T, w0 + dw * T, n0 + dn * T
    M = math.radians((L - wbar + 180) % 360 - 180)
    w = math.radians(wbar - node)
    O = math.radians(node)
    E = M + e * math.sin(M)
    for _ in range(12):
        E -= (E - e * math.sin(E) - M) / (1 - e * math.cos(E))
    xp, yp = a * (math.cos(E) - e), a * math.sqrt(1 - e * e) * math.sin(E)
    x = (math.cos(w) * math.cos(O) - math.sin(w) * math.sin(O) * math.cos(I)) * xp + \
        (-math.sin(w) * math.cos(O) - math.cos(w) * math.sin(O) * math.cos(I)) * yp
    y = (math.cos(w) * math.sin(O) + math.sin(w) * math.cos(O) * math.cos(I)) * xp + \
        (-math.sin(w) * math.sin(O) + math.cos(w) * math.cos(O) * math.cos(I)) * yp
    z = math.sin(w) * math.sin(I) * xp + math.cos(w) * math.sin(I) * yp
    return np.array([x, y, z])


